"""TradingView connection.

TradingView has no free API for reading its data, so the connection works
the other way round:

1. `pine_script()` writes a Pine Script v5 strategy with the same entry and
   exit rules as the entry timer and time machine. Paste it into TradingView's
   Pine Editor (free plan) to see every signal on the chart and replay it in
   the Strategy Tester. The Pine version is close but not identical: Pine
   seeds its averages differently and sets the stop from the signal bar's
   close, because the fill price is not known until the next bar.

2. Its alerts send a JSON message. On a TradingView plan with webhooks, point
   the alert at POST /api/desk/tradingview on the dashboard (it must be
   reachable from the internet, for example through a tunnel) and set
   DESK_WEBHOOK_SECRET to the same secret. Received alerts are logged and
   forwarded to your notifications. They never place orders.

3. Chart data exported from TradingView (chart menu > Export chart data) can
   be read by every desk tool as a CSV file.
"""

from __future__ import annotations

import hmac
import os

from . import strategies
from .exits import ExitRules


def pine_script(rules: ExitRules | None = None, secret: str = "change-me") -> str:
    r = rules or ExitRules()
    return f"""//@version=5
// Trading desk rules {strategies.RULES_VERSION} / exits-v1, generated by nse_research.desk.
// Research and paper trading only. Past results do not guarantee future profit.
strategy("Desk entry and exit rules", overlay=true, initial_capital=10000,
     default_qty_type=strategy.percent_of_equity, default_qty_value=10,
     commission_type=strategy.commission.percent, commission_value={r.cost_bps / 100:g})

stopAtr  = input.float({r.stop_atr}, "Initial stop (ATR)")
targetR  = input.float({r.target_r or 0}, "Target (R, 0 = none)")
trailAtr = input.float({r.trail_atr or 0}, "Trailing stop (ATR, 0 = none)")
maxBars  = input.int({r.max_bars}, "Time stop (bars)")
useBrk   = input.bool(true, "breakout20")
usePb    = input.bool(true, "pullback")
useNr7   = input.bool(true, "nr7")
secret   = input.string("{secret}", "Webhook secret")

sma50  = ta.sma(close, 50)
sma200 = ta.sma(close, 200)
ema20  = ta.ema(close, 20)
atr    = ta.atr(14)
rsi    = ta.rsi(close, 14)
relVol = volume / ta.sma(volume, 20)

uptrend   = close > sma200 and sma50 > sma200
notExt    = rsi < {strategies.RSI_MAX} and (close - ema20) < {strategies.EXTENDED_ATR} * atr
priorHigh = ta.highest(high, {strategies.BREAKOUT_BARS})[1]
brk = close > priorHigh and (na(volume) or relVol >= {strategies.VOLUME_MULT})
pb  = low <= ema20 and close > ema20 and close > open and close > close[1]
rng = high - low
nr7 = rng[1] < ta.lowest(rng, 6)[2] and close > high[1]
sig = uptrend and notExt and ((useBrk and brk) or (usePb and pb) or (useNr7 and nr7))

var float stopPx = na
var float targetPx = na
var float hiSince = na
var float sigAtr = na
var int entryBar = na

if sig and strategy.position_size == 0
    sigAtr := atr
    stopPx := close - stopAtr * atr
    targetPx := targetR > 0 ? close + targetR * stopAtr * atr : na
    hiSince := na
    strategy.entry("Long", strategy.long)
    alert('{{"secret":"' + secret + '","symbol":"' + syminfo.ticker + '","event":"entry_rules_met","price":' + str.tostring(close) + '}}', alert.freq_once_per_bar_close)

if strategy.position_size > 0
    if strategy.position_size[1] == 0
        entryBar := bar_index
    hiSince := na(hiSince) ? high : math.max(hiSince, high)
    if trailAtr > 0
        stopPx := math.max(stopPx, hiSince - trailAtr * sigAtr)
    if bar_index - entryBar >= maxBars - 1
        strategy.close("Long", comment="time stop")
        alert('{{"secret":"' + secret + '","symbol":"' + syminfo.ticker + '","event":"time_stop","price":' + str.tostring(close) + '}}', alert.freq_once_per_bar_close)

strategy.exit("Exit", "Long", stop=stopPx, limit=targetPx)

plotshape(sig, "Entry rules met", shape.triangleup, location.belowbar, color.new(color.teal, 0), size=size.small)
plot(strategy.position_size > 0 ? stopPx : na, "Stop", color.new(color.red, 0), style=plot.style_linebr)
plot(strategy.position_size > 0 ? targetPx : na, "Target", color.new(color.green, 0), style=plot.style_linebr)
plot(sma50, "SMA 50", color.new(color.orange, 40))
plot(sma200, "SMA 200", color.new(color.blue, 40))
"""


def verify_webhook(payload: dict, env=os.environ) -> bool:
    want = env.get("DESK_WEBHOOK_SECRET")
    return bool(want) and hmac.compare_digest(str(payload.get("secret", "")), want)
