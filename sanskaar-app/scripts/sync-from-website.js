#!/usr/bin/env node
/* ==========================================================================
   Sync the app with the SANSKAAR website (../sanskaar)
   --------------------------------------------------------------------------
   The website stays the single source of truth. This script copies into the
   app:
     - the catalogue (js/catalog-data.js)      -> src/data/catalog.json
     - business settings (SANSKAAR.config)     -> src/data/catalog.json
     - the illustrated previews (js/art.js)    -> src/data/art.generated.js
     - every photo under images/               -> assets/site/...
       plus a require() map Metro can bundle   -> src/data/images.generated.ts
     - prices and sizes for the payments API   -> ../sanskaar-api/data/catalog.json

   Run it after editing products, prices or photos on the website:
     npm run sync
   ========================================================================== */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const APP = path.resolve(__dirname, "..");
const SITE = path.resolve(APP, "../sanskaar");
const OUT_DATA = path.join(APP, "src/data");
const OUT_IMG = path.join(APP, "assets/site");

const read = f => fs.readFileSync(path.join(SITE, f), "utf8");

// 1. Catalogue: run the website's data file in a sandbox whose global is `window`,
//    just like a browser
const sandbox = vm.createContext({});
sandbox.window = sandbox;
vm.runInContext(read("js/catalog-data.js"), sandbox);
const S = JSON.parse(JSON.stringify(sandbox.SANSKAAR));

// 2. Business settings live at the top of app.js
const cfgSrc = read("js/app.js").match(/SANSKAAR\.config\s*=\s*(\{[\s\S]*?\n\});/);
if (!cfgSrc) throw new Error("Could not find SANSKAAR.config in js/app.js");
const config = vm.runInNewContext(`(${cfgSrc[1]})`);

const catalog = {
  config,
  categories: S.categories,
  occasions: S.occasions,
  collections: S.collections,
  colors: S.colors,
  products: S.products
};
fs.mkdirSync(OUT_DATA, { recursive: true });
fs.writeFileSync(path.join(OUT_DATA, "catalog.json"), JSON.stringify(catalog, null, 1) + "\n");

// The payments API prices orders from the same catalogue (never from the phone)
const API_DATA = path.resolve(APP, "../sanskaar-api/data");
fs.mkdirSync(API_DATA, { recursive: true });
fs.writeFileSync(path.join(API_DATA, "catalog.json"), JSON.stringify({
  config: { freeShippingAbove: config.freeShippingAbove, shippingFee: config.shippingFee },
  products: S.products.map(p => ({ id: p.id, name: p.name, price: p.price, sizes: p.sizes }))
}, null, 1) + "\n");

// 3. Illustrated previews: same drawing code, exported as a CommonJS module
const art = read("js/art.js").replace("window.SanskaarArt =", "module.exports =");
if (!art.includes("module.exports =")) throw new Error("Could not find window.SanskaarArt in js/art.js");
fs.writeFileSync(path.join(OUT_DATA, "art.generated.js"),
  "// GENERATED by scripts/sync-from-website.js from sanskaar/js/art.js — do not edit.\n" + art);

// 4. Photos: copy every jpg/png and build a static require() map
fs.rmSync(OUT_IMG, { recursive: true, force: true });
const entries = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    if (!/\.(jpe?g|png|webp)$/i.test(name)) continue;
    const rel = path.relative(path.join(SITE, "images"), full).split(path.sep).join("/");
    const dest = path.join(OUT_IMG, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(full, dest);
    entries.push(rel);
  }
})(path.join(SITE, "images"));

fs.writeFileSync(path.join(OUT_DATA, "images.generated.ts"),
  "// GENERATED by scripts/sync-from-website.js from sanskaar/images — do not edit.\n" +
  "// Keys are paths relative to the website's images/ folder.\n" +
  "export const images: Record<string, number> = {\n" +
  entries.map(rel => `  ${JSON.stringify(rel)}: require(${JSON.stringify("../../assets/site/" + rel)}),`).join("\n") +
  "\n};\n");

console.log(`Synced ${S.products.length} products, ${S.collections.length} collections and ${entries.length} photos from ${path.relative(process.cwd(), SITE) || "."}`);
